const PREFIX = [['Onbekend schema: ', 'مخطط غير معروف: '], ['Onbekend vak: ', 'مادة غير معروفة: ']]

export function serverError (msg, lang) {
  if (lang !== 'ar' || !msg) return msg
  if (AR[msg]) return AR[msg]
  for (const [nl, ar] of PREFIX) if (msg.startsWith(nl)) return ar + msg.slice(nl.length)
  return msg
}
